/**
 * Basic perulangan menggunakan for
 * Tuliskan potongan code di dalam main method
 * lengkapi hingga menjadi program lengkap
 * hingga dapat di compile dan execute
 * perbaiki jika terdapat error
 */
int[] a = {1,2,3,4};
for(int x = 0; x < a.length; x++)
    System.out.print(a[x]);
for(int n : a)
    System.out.print(n);